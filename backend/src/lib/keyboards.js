// =============================================================================
// src/lib/keyboards.js
// این فایل «دکمه‌های تکرارشونده» ربات را در یک جا می‌سازد تا در فایل‌های
// دیگر مجبور نباشیم هربار از صفر بنویسیمشان.
//
// نکته‌ی مهم درباره‌ی دو نوع دکمه در تلگرام (چون در کل پروژه استفاده می‌شود):
//   ۱. Keyboard (کیبورد معمولی/Reply Keyboard): دکمه‌هایی که همیشه پایین
//      صفحه، بالای جعبه‌ی تایپ، ثابت می‌مانند. مثل «🛍 محصولات» در منوی اصلی.
//      وقتی کاربر رویشان بزند، یک پیام متنی عادی برای ربات ارسال می‌شود.
//   ۲. InlineKeyboard (کیبورد شیشه‌ای/درون‌خطی): دکمه‌هایی که مستقیم زیرِ
//      یک پیام خاص چسبیده‌اند (مثلا زیر لیست محصولات). زدنشان یک
//      callback_query می‌فرستد، نه پیام متنی جدید.
// =============================================================================

import { Keyboard, InlineKeyboard } from "grammy";

/**
 * کیبورد اصلی پایین صفحه برای مشتری (و در صورت ادمین‌بودن، دکمه‌ی پنل مدیریت هم اضافه می‌شود).
 *
 * @param {boolean} isAdmin - آیا این کاربر مالک یا همکار فروشگاه است؟
 * @returns {Keyboard}
 */
export function mainMenuKeyboard(isAdmin) {
  const kb = new Keyboard()
    .text("🛍 محصولات").text("🔍 جستجوی محصول").row()
    .text("👤 حساب کاربری").text("☎️ پشتیبانی").row();

  // دکمه‌ی ورود به پنل مدیریت فقط برای مالک/همکاران نمایش داده می‌شود
  // تا مشتری‌های عادی اصلا آن را نبینند (لایه‌ی اول امنیت؛ لایه‌ی دوم هم
  // در خودِ کد بررسی دسترسی است، چون متن دکمه را هرکسی می‌تواند تایپ کند)
  if (isAdmin) {
    kb.text("🔧 پنل مدیریت").row();
  }

  // resized یعنی اندازه‌ی دکمه‌ها با صفحه‌ی گوشی هماهنگ شود (شبیه ویدیوی نمونه)
  return kb.resized();
}

/**
 * کیبورد پایین صفحه‌ی مخصوص «داخل پنل مدیریت» — با زدن هرکدام وارد آن بخش می‌شویم
 * @returns {Keyboard}
 */
export function adminMenuKeyboard() {
  return new Keyboard()
    .text("📦 مدیریت محصولات").text("💰 بخش مالی").row()
    .text("📑 مدیریت سفارشات").text("👥 مدیریت کاربران").row()
    .text("⚙️ تنظیمات عمومی").text("📊 دریافت گزارش").row()
    .text("📱 اتصال اپ مدیریت").row()
    .text("🔙 بازگشت")
    .resized();
}

/**
 * یک کیبورد شیشه‌ای ساده با دو دکمه‌ی «بله / خیر» برای تاییدیه‌های حساس
 * (مثلا قبل از حذف یک محصول)
 *
 * @param {string} yesData - مقدار callback_data برای دکمه‌ی بله
 * @param {string} noData - مقدار callback_data برای دکمه‌ی خیر
 */
export function confirmKeyboard(yesData, noData) {
  return new InlineKeyboard()
    .text("✅ بله، مطمئنم", yesData)
    .text("❌ انصراف", noData);
}

/**
 * یک دکمه‌ی بازگشت تنها، برای زیر منوهای شیشه‌ای
 * @param {string} backData - مقدار callback_data دکمه‌ی بازگشت
 */
export function backOnlyKeyboard(backData) {
  return new InlineKeyboard().text("🔙 بازگشت", backData);
}
